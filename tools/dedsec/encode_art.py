"""Encode approved PNG pixels as deterministic 2-bit flash assets; not needed to build firmware."""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SPECS = (("Logo", "logo.png", 160, 0.60), ("Wifi", "wifi.png", 128, 0.75),
         ("Bluetooth", "bluetooth.png", 128, 0.75), ("Config", "config.png", 128, 0.75),
         ("Rf", "rf.png", 128, 0.75), ("Nrf24", "nrf24.png", 128, 0.75),
         ("Lora", "lora.png", 128, 0.75), ("Fm", "fm.png", 128, 0.75),
         ("Infrared", "ir.png", 128, 0.75), ("Ethernet", "ethernet.png", 128, 0.75),
         ("Gps", "gps.png", 128, 0.75), ("Rfid", "rfid.png", 128, 0.75),
         ("Files", "files.png", 128, 0.75), ("Scripts", "scripts.png", 128, 0.75),
         ("Clock", "clock.png", 128, 0.75), ("Others", "others.png", 128, 0.75))


def pack(levels: list[int], width: int, height: int) -> bytes:
    if width < 1 or height < 1 or len(levels) != width * height:
        raise ValueError("Invalid dimensions")
    stride = (width + 3) // 4
    result = bytearray(stride * height)
    for y in range(height):
        for x in range(width):
            level = levels[y * width + x]
            if not 0 <= level <= 3:
                raise ValueError("Invalid 2-bit level")
            result[y * stride + x // 4] |= level << (6 - 2 * (x % 4))
    return bytes(result)


def unpack(data: bytes, width: int, height: int) -> list[int]:
    stride = (width + 3) // 4
    if width < 1 or height < 1 or len(data) != stride * height:
        raise ValueError("Invalid packed length")
    return [(data[y * stride + x // 4] >> (6 - 2 * (x % 4))) & 3
            for y in range(height) for x in range(width)]


def generate(check: bool = False) -> None:
    directory = ROOT / "media/dedsec"
    lines = ["// Generated by tools/dedsec/encode_art.py. Approved artwork; see media/dedsec/README.md.",
             "// Four luminance levels, four pixels per byte, MSB first, rows independently padded."]
    metadata = []
    for name, filename, maximum, gamma in SPECS:
        source = directory / "source" / filename
        with Image.open(source) as image:
            image = image.convert("RGB").convert("L")
            # Preserve the supplied composition. Lanczos reduces the scan-like
            # texture; fixed gamma keeps the dark first logo readable on the TFT.
            image.thumbnail((maximum, maximum), Image.Resampling.LANCZOS)
            lut = [min(3, int(((value / 255) ** gamma * 255 + 42) // 85)) for value in range(256)]
            levels = list(image.point(lut).get_flattened_data())
        width, height = image.size
        data = pack(levels, width, height)
        if unpack(data, width, height) != levels:
            raise ValueError("Packed asset failed round trip")
        lines.append(f"static const uint8_t {name}Pixels[] PROGMEM = {{")
        lines.extend("    " + ", ".join(f"0x{value:02X}" for value in data[pos:pos + 20]) + ","
                     for pos in range(0, len(data), 20))
        lines.extend(["};", "static constexpr PackedArt %sArt = {%sPixels, %d, %d};" %
                      (name, name, width, height), ""])
        metadata.append({"name": name, "source": f"source/{filename}", "width": width, "height": height,
                         "bits_per_pixel": 2, "flash_bytes": len(data), "gamma": gamma,
                         "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                         "packed_sha256": hashlib.sha256(data).hexdigest()})
        if not check:
            preview = Image.new("L", (width, height))
            preview.putdata([value * 85 for value in levels])
            (directory / "preview").mkdir(parents=True, exist_ok=True)
            preview.save(directory / "preview" / filename, optimize=True)
    outputs = {ROOT / "src/core/dedsec_art_data.inc": "\n".join(lines).rstrip() + "\n",
               directory / "assets.json": json.dumps(metadata, indent=2) + "\n"}
    for path, value in outputs.items():
        if check:
            if path.read_text(encoding="utf-8") != value:
                raise ValueError(f"Stale generated asset: {path}")
        else:
            path.write_text(value, encoding="utf-8")
    print(json.dumps({"assets": len(metadata), "packed_flash_bytes": sum(item["flash_bytes"] for item in metadata)}, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
